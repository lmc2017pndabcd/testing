import path from 'node:path';
import fsp from 'node:fs/promises';
import { csvToObjects, ensureDir, execCapture, parseCsvRows, percentile, toNumber, which } from '../util.js';
import { simulatePerf } from './simulate.js';

const DEFAULTS = {
  host: 'https://httpbin.org',
  threads: 20,
  rampTime: 5,
  duration: 60,
  loopCount: 1,
  paths: 'GET / 1\nGET /get 1',
};

const xmlEscape = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

function parseTarget(host) {
  try {
    const u = new URL(String(host));
    return {
      protocol: u.protocol.replace(':', '') || 'https',
      domain: u.hostname,
      port: u.port || (u.protocol === 'https:' ? '443' : '80'),
      basePath: u.pathname && u.pathname !== '/' ? u.pathname.replace(/\/$/, '') : '',
    };
  } catch {
    return { protocol: 'https', domain: String(host || 'localhost'), port: '443', basePath: '' };
  }
}

function parsePaths(text) {
  return String(text || '')
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((line) => {
      const parts = line.split(/\s+/);
      let method = 'GET';
      let rest = parts;
      if (/^(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)$/i.test(parts[0])) {
        method = parts[0].toUpperCase();
        rest = parts.slice(1);
      }
      const weight = rest.length > 1 && /^\d+(\.\d+)?$/.test(rest[rest.length - 1])
        ? Number(rest.pop())
        : 1;
      const p = rest.join(' ');
      return { method, path: p.startsWith('/') ? p : `/${p}`, weight: weight || 1 };
    })
    .filter((t) => t.path);
}

/** Render a complete JMeter test plan (.jmx) from the UI configuration. */
function renderJmx({ target, threads, rampTime, duration, loopCount, samplers, name = 'TestBench Plan' }) {
  const samplerXml = samplers
    .map(
      (s) => `        <HTTPSamplerProxy guiclass="HttpTestSampleGui" testclass="HTTPSamplerProxy" testname="${xmlEscape(`${s.method} ${s.path}`)}" enabled="true">
          <elementProp name="HTTPsampler.Arguments" elementType="Arguments" guiclass="HTTPArgumentsPanel" testclass="Arguments" testname="User Defined Variables" enabled="true">
            <collectionProp name="Arguments.arguments"/>
          </elementProp>
          <stringProp name="HTTPSampler.domain">${xmlEscape(target.domain)}</stringProp>
          <stringProp name="HTTPSampler.port">${xmlEscape(target.port)}</stringProp>
          <stringProp name="HTTPSampler.protocol">${xmlEscape(target.protocol)}</stringProp>
          <stringProp name="HTTPSampler.path">${xmlEscape(s.path)}</stringProp>
          <stringProp name="HTTPSampler.method">${xmlEscape(s.method)}</stringProp>
          <boolProp name="HTTPSampler.follow_redirects">true</boolProp>
          <boolProp name="HTTPSampler.auto_redirects">false</boolProp>
          <boolProp name="HTTPSampler.use_keepalive">true</boolProp>
          <boolProp name="HTTPSampler.DO_MULTIPART_POST">false</boolProp>
          <stringProp name="HTTPSampler.embedded_url_re"></stringProp>
          <stringProp name="HTTPSampler.connect_timeout"></stringProp>
          <stringProp name="HTTPSampler.response_timeout"></stringProp>
        </HTTPSamplerProxy>
        <hashTree/>`,
    )
    .join('\n');

  const weightedController = samplers.length > 1
    ? `      <RandomController guiclass="RandomControlGui" testclass="RandomController" testname="随机接口" enabled="true">
        <intProp name="InterleaveControl.style">1</intProp>
      </RandomController>
      <hashTree>
${samplerXml}
      </hashTree>`
    : `      <hashTree>
${samplerXml}
      </hashTree>`;

  return `<?xml version="1.0" encoding="UTF-8"?>
<jmeterTestPlan version="1.2" properties="5.0" jmeter="5.6.3">
  <hashTree>
    <TestPlan guiclass="TestPlanGui" testclass="TestPlan" testname="${xmlEscape(name)}" enabled="true">
      <stringProp name="TestPlan.comments">Generated by TestBench</stringProp>
      <boolProp name="TestPlan.functional_mode">false</boolProp>
      <boolProp name="TestPlan.serialize_threadgroups">false</boolProp>
      <elementProp name="TestPlan.user_defined_variables" elementType="Arguments" guiclass="ArgumentsPanel" testclass="Arguments" testname="User Defined Variables" enabled="true">
        <collectionProp name="Arguments.arguments"/>
      </elementProp>
    </TestPlan>
    <hashTree>
      <ThreadGroup guiclass="ThreadGroupGui" testclass="ThreadGroup" testname="并发线程组" enabled="true">
        <stringProp name="ThreadGroup.on_sample_error">continue</stringProp>
        <elementProp name="ThreadGroup.main_controller" elementType="LoopController" guiclass="LoopControlPanel" testclass="LoopController" testname="循环控制器" enabled="true">
          <boolProp name="LoopController.continue_forever">false</boolProp>
          <stringProp name="LoopController.loops">${xmlEscape(loopCount)}</stringProp>
        </elementProp>
        <stringProp name="ThreadGroup.num_threads">${xmlEscape(threads)}</stringProp>
        <stringProp name="ThreadGroup.ramp_time">${xmlEscape(rampTime)}</stringProp>
        <boolProp name="ThreadGroup.scheduler">true</boolProp>
        <stringProp name="ThreadGroup.duration">${xmlEscape(duration)}</stringProp>
        <stringProp name="ThreadGroup.delay">0</stringProp>
        <boolProp name="ThreadGroup.same_user_on_next_iteration">true</boolProp>
      </ThreadGroup>
      <hashTree>
        <HeaderManager guiclass="HeaderPanel" testclass="HeaderManager" testname="HTTP 信息头管理器" enabled="true">
          <collectionProp name="HeaderManager.headers">
            <elementProp name="" elementType="Header">
              <stringProp name="Header.name">User-Agent</stringProp>
              <stringProp name="Header.value">TestBench-JMeter/1.0</stringProp>
            </elementProp>
          </collectionProp>
        </HeaderManager>
        <hashTree/>
${weightedController}
      </hashTree>
    </hashTree>
  </hashTree>
</jmeterTestPlan>
`;
}

export default {
  id: 'jmeter',
  name: 'Apache JMeter',
  tagline: '企业级协议压测工具，支持复杂场景编排',
  category: 'performance',
  accent: '#f7b955',
  docs: 'https://jmeter.apache.org',
  install: { cmd: 'brew install jmeter', hint: '本机已检测到 Java，安装 JMeter 后即可执行真实压测' },
  binary: 'jmeter',
  defaults: DEFAULTS,

  fields: [
    { key: 'host', label: '目标地址', type: 'text', required: true, default: DEFAULTS.host, placeholder: 'https://example.com', group: '目标' },
    { key: 'paths', label: '请求路径', type: 'textarea', rows: 5, default: DEFAULTS.paths, group: '目标',
      help: '每行一条：METHOD 路径 [权重]。多个接口由随机控制器按权重分流。' },
    { key: 'threads', label: '线程数(并发)', type: 'number', min: 1, max: 100000, default: DEFAULTS.threads, group: '负载' },
    { key: 'rampTime', label: 'Ramp-up(秒)', type: 'number', min: 0, max: 86400, default: DEFAULTS.rampTime, group: '负载' },
    { key: 'duration', label: '持续时间(秒)', type: 'number', min: 1, max: 86400, default: DEFAULTS.duration, group: '负载' },
    { key: 'loopCount', label: '循环次数', type: 'number', min: 1, max: 100000, default: DEFAULTS.loopCount, group: '负载',
      help: '启用调度器时以持续时间为准，循环次数作为单线程上限' },
    { key: 'extraArgs', label: '附加 CLI 参数', type: 'text', default: '', group: '高级', placeholder: '-Jjmeter.save.saveservice.thread_counts=true' },
  ],

  async detect() {
    const bin = await which('jmeter');
    const java = await which('java');
    if (!bin) {
      return {
        available: false, mode: 'demo', binary: null,
        detail: java
          ? '未检测到 jmeter 命令（Java 已就绪），运行将使用演示模式'
          : '未检测到 jmeter 与 java，运行将使用演示模式',
        install: 'brew install jmeter',
      };
    }
    const r = await execCapture(bin, ['--version'], { timeoutMs: 25000 });
    const line = (r.stdout + r.stderr).split('\n').find((l) => /version/i.test(l)) || '';
    return {
      available: true, mode: 'real', binary: bin,
      version: line.trim() || 'unknown',
      detail: '已检测到 JMeter，可执行真实压测',
    };
  },

  async prepare({ config, runDir, dataset }) {
    const cfg = { ...DEFAULTS, ...config };
    const target = parseTarget(cfg.host);
    let samplers = parsePaths(cfg.paths);

    if (dataset?.rows?.length) {
      const fromDataset = dataset.rows
        .map((r) => ({
          method: String(r.method || 'GET').toUpperCase(),
          path: String(r.path || r.url || '/'),
        }))
        .filter((s) => s.path);
      if (fromDataset.length) samplers = fromDataset;
    }
    if (!samplers.length) {
      samplers = [{ method: 'GET', path: target.basePath || '/' }];
    }
    samplers = samplers.map((s) => ({
      method: s.method,
      path: target.basePath && !s.path.startsWith(target.basePath) ? `${target.basePath}${s.path}` : s.path,
    }));

    await ensureDir(runDir);
    const jmxPath = path.join(runDir, 'plan.jmx');
    await fsp.writeFile(
      jmxPath,
      renderJmx({
        target,
        threads: cfg.threads,
        rampTime: cfg.rampTime,
        duration: cfg.duration,
        loopCount: cfg.loopCount,
        samplers,
      }),
      'utf8',
    );

    const jtl = path.join(runDir, 'results.jtl');
    const args = [
      '-n',
      '-t', jmxPath,
      '-l', jtl,
      '-j', path.join(runDir, 'jmeter.log'),
      '-Jjmeter.save.saveservice.output_format=csv',
      '-Jjmeter.save.saveservice.print_field_names=true',
      '-Jjmeter.save.saveservice.thread_counts=true',
    ];
    if (cfg.extraArgs) args.push(...String(cfg.extraArgs).split(/\s+/).filter(Boolean));

    return {
      command: 'jmeter',
      args,
      cwd: runDir,
      artifacts: { jtl, jmxPath },
      targets: samplers.map((s) => ({ method: s.method, path: s.path, weight: 1 })),
      durationSec: Number(cfg.duration),
    };
  },

  async simulate({ config, targets }) {
    return simulatePerf({
      users: Number(config.threads) || 20,
      spawnRate: Math.max(0.5, (Number(config.threads) || 20) / Math.max(1, Number(config.rampTime) || 5)),
      durationSec: Number(config.duration) || 60,
      targets,
      engine: 'jmeter',
    });
  },

  async parse({ runDir, prepared }) {
    const jtl = prepared?.artifacts?.jtl ?? path.join(runDir, 'results.jtl');
    const out = { metrics: [], series: [], seriesKeys: [], table: null, report: {} };
    let raw;
    try {
      raw = await fsp.readFile(jtl, 'utf8');
    } catch {
      return out;
    }

    const { columns, rows } = csvToObjects(raw);
    if (!rows.length) return out;

    // JMeter can be configured to omit field names; fall back to positional
    // parsing (the default field order) instead of losing the first record.
    const hasHeader = columns.some((c) => c.trim().toLowerCase() === 'elapsed');
    let records = rows;
    if (!hasHeader) {
      const COLS = ['timeStamp', 'elapsed', 'label', 'responseCode', 'responseMessage', 'threadName',
        'dataType', 'success', 'failureMessage', 'bytes', 'sentBytes', 'grpThreads', 'allThreads',
        'URL', 'Latency', 'IdleTime', 'Connect'];
      const rawRows = parseCsvRows(raw);
      records = rawRows
        .filter((r) => r.length >= 4)
        .map((r) => Object.fromEntries(COLS.map((name, i) => [name, r[i] ?? ''])));
    }

    const t0 = Math.min(...records.map((r) => toNumber(r.timeStamp, NaN)).filter(Number.isFinite));
    const startMs = Number.isFinite(t0) ? t0 : 0;
    const byLabel = new Map();
    const bySecond = new Map();
    const latencies = [];

    for (const r of records) {
      const elapsed = toNumber(r.elapsed);
      const success = String(r.success).toLowerCase() !== 'false' && toNumber(r.responseCode, 200) < 400;
      const label = r.label || r.URL || 'unknown';
      latencies.push(elapsed);

      const agg = byLabel.get(label) ?? { name: label, requests: 0, failures: 0, elapsed: [] };
      agg.requests += 1;
      if (!success) agg.failures += 1;
      if (agg.elapsed.length < 20000) agg.elapsed.push(elapsed);
      byLabel.set(label, agg);

      const sec = Math.max(0, Math.round((toNumber(r.timeStamp) - startMs) / 1000));
      const bucket = bySecond.get(sec) ?? { t: sec, requests: 0, errors: 0, elapsed: [], threads: 0 };
      bucket.requests += 1;
      if (!success) bucket.errors += 1;
      bucket.elapsed.push(elapsed);
      bucket.threads = Math.max(bucket.threads, toNumber(r.allThreads ?? r.grpThreads, 1));
      bySecond.set(sec, bucket);
    }

    const sortedAll = latencies.slice().sort((a, b) => a - b);
    const totalRequests = records.length;
    const failures = [...byLabel.values()].reduce((s, v) => s + v.failures, 0);
    const avg = sortedAll.reduce((s, v) => s + v, 0) / Math.max(1, sortedAll.length);
    const durationSec = Math.max(1, Math.round((Math.max(...[...bySecond.keys()], 0) + 1)));

    out.metrics = [
      { key: 'requests', label: '总请求数', value: totalRequests, format: 'int' },
      { key: 'rps', label: '平均 RPS', value: Number((totalRequests / durationSec).toFixed(2)), format: 'float' },
      { key: 'avg', label: '平均响应(ms)', value: Math.round(avg), format: 'int' },
      { key: 'p95', label: 'P95(ms)', value: Math.round(percentile(sortedAll, 95)), format: 'int' },
      { key: 'p99', label: 'P99(ms)', value: Math.round(percentile(sortedAll, 99)), format: 'int' },
      { key: 'errorRate', label: '错误率', value: Number(((failures / Math.max(1, totalRequests)) * 100).toFixed(2)), format: 'percent' },
    ];

    out.series = [...bySecond.values()]
      .sort((a, b) => a.t - b.t)
      .map((b) => {
        const s = b.elapsed.slice().sort((x, y) => x - y);
        return {
          t: b.t,
          rps: Number((b.requests / 1).toFixed(2)),
          avg: Math.round(s.reduce((x, y) => x + y, 0) / Math.max(1, s.length)),
          p95: Math.round(percentile(s, 95)),
          p99: Math.round(percentile(s, 99)),
          users: b.threads,
          errors: b.errors,
          requests: b.requests,
        };
      });
    out.seriesKeys = [
      { key: 'rps', label: 'RPS', color: '#4f9cf9', axis: 'left' },
      { key: 'avg', label: '平均延迟(ms)', color: '#f7b955', axis: 'right' },
      { key: 'p95', label: 'P95(ms)', color: '#e5679b', axis: 'right' },
    ];

    out.table = {
      title: '请求明细',
      columns: [
        { key: 'name', label: '请求' },
        { key: 'requests', label: '请求数', align: 'right', format: 'int' },
        { key: 'failures', label: '失败', align: 'right', format: 'int' },
        { key: 'avg', label: '平均(ms)', align: 'right', format: 'int' },
        { key: 'p95', label: 'P95(ms)', align: 'right', format: 'int' },
        { key: 'rps', label: 'RPS', align: 'right', format: 'float' },
      ],
      rows: [...byLabel.values()].map((v) => {
        const s = v.elapsed.slice().sort((a, b) => a - b);
        return {
          name: v.name,
          requests: v.requests,
          failures: v.failures,
          avg: Math.round(s.reduce((x, y) => x + y, 0) / Math.max(1, s.length)),
          p95: Math.round(percentile(s, 95)),
          rps: Number((v.requests / durationSec).toFixed(2)),
        };
      }),
    };

    out.report = {
      totalRequests,
      failures,
      errorRate: Number(((failures / Math.max(1, totalRequests)) * 100).toFixed(3)),
      avg: Math.round(avg),
      min: Math.round(sortedAll[0] ?? 0),
      max: Math.round(sortedAll[sortedAll.length - 1] ?? 0),
      p50: Math.round(percentile(sortedAll, 50)),
      p90: Math.round(percentile(sortedAll, 90)),
      p95: Math.round(percentile(sortedAll, 95)),
      p99: Math.round(percentile(sortedAll, 99)),
      durationSec,
      jtl,
    };
    return out;
  },
};
