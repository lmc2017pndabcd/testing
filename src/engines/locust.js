import path from 'node:path';
import fsp from 'node:fs/promises';
import { csvToObjects, ensureDir, execCapture, toNumber, which } from '../util.js';
import { simulatePerf } from './simulate.js';

const DEFAULTS = {
  host: 'https://httpbin.org',
  users: 20,
  spawnRate: 4,
  duration: 60,
  paths: 'GET / 3\nGET /get 2',
};

function parsePaths(text) {
  return String(text || '')
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((line) => {
      const parts = line.split(/\s+/);
      let method = 'GET';
      let rest = parts;
      if (/^(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)$/i.test(parts[0])) {
        method = parts[0].toUpperCase();
        rest = parts.slice(1);
      }
      const weight = rest.length > 1 && /^\d+(\.\d+)?$/.test(rest[rest.length - 1])
        ? Number(rest.pop())
        : 1;
      const p = rest.join(' ');
      return { method, path: p.startsWith('/') ? p : `/${p}`, weight: weight || 1 };
    })
    .filter((t) => t.path);
}

/** Build a locustfile from the UI config so users never hand-write Python. */
function renderLocustfile(targets, { waitMin = 0.5, waitMax = 2 } = {}) {
  const tasks = targets
    .map((t, i) => {
      const pyMethod = t.method.toLowerCase();
      const safe = t.path.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
      const body =
        t.method === 'GET'
          ? `self.client.get("${safe}", name="${t.method} ${safe}")`
          : `self.client.request("${t.method}", "${safe}", json={}, name="${t.method} ${safe}")`;
      return [
        `    @task(${t.weight})`,
        `    def task_${i}_${pyMethod}(self):`,
        `        ${body}`,
        '',
      ].join('\n');
    })
    .join('\n');

  return [
    '# Auto-generated by TestBench. Edit the UI config instead of this file.',
    'from locust import HttpUser, task, between',
    '',
    '',
    'class GeneratedUser(HttpUser):',
    `    wait_time = between(${waitMin}, ${waitMax})`,
    '',
    tasks,
  ].join('\n');
}

export default {
  id: 'locust',
  name: 'Locust',
  tagline: 'Python 编写的高并发负载测试工具',
  category: 'performance',
  accent: '#5ad1a8',
  docs: 'https://docs.locust.io',
  install: { cmd: 'pip install locust', hint: '需要 Python 3.9+，安装后 node 服务会自动识别' },
  binary: 'locust',
  defaults: DEFAULTS,

  fields: [
    { key: 'host', label: '目标地址', type: 'text', required: true, default: DEFAULTS.host, placeholder: 'https://example.com', group: '目标' },
    { key: 'paths', label: '请求路径', type: 'textarea', rows: 5, default: DEFAULTS.paths, group: '目标',
      help: '每行一条：METHOD 路径 [权重]，例如 “GET /api/items 3”', placeholder: 'GET / 3' },
    { key: 'users', label: '并发用户数', type: 'number', min: 1, max: 100000, default: DEFAULTS.users, group: '负载' },
    { key: 'spawnRate', label: '启动速率(用户/秒)', type: 'number', min: 0.1, max: 10000, step: 0.1, default: DEFAULTS.spawnRate, group: '负载' },
    { key: 'duration', label: '持续时间(秒)', type: 'number', min: 5, max: 86400, default: DEFAULTS.duration, group: '负载' },
    { key: 'waitMin', label: '最小等待(秒)', type: 'number', min: 0, max: 60, step: 0.1, default: 0.5, group: '高级' },
    { key: 'waitMax', label: '最大等待(秒)', type: 'number', min: 0, max: 600, step: 0.1, default: 2, group: '高级' },
    { key: 'extraArgs', label: '附加 CLI 参数', type: 'text', default: '', group: '高级', placeholder: '--tags smoke' },
  ],

  async detect() {
    const bin = await which('locust');
    if (!bin) {
      return {
        available: false, mode: 'demo', binary: null,
        detail: '未检测到 locust 命令，运行将使用演示模式（合成数据）',
        install: 'pip install locust',
      };
    }
    const r = await execCapture(bin, ['--version'], { timeoutMs: 15000 });
    return {
      available: true, mode: 'real', binary: bin,
      version: (r.stdout + r.stderr).trim().split('\n')[0] || 'unknown',
      detail: '已检测到 locust，可执行真实负载测试',
    };
  },

  async prepare({ config, runDir, dataset }) {
    const cfg = { ...DEFAULTS, ...config };
    let targets = parsePaths(cfg.paths);

    // A dataset of endpoints can drive the request mix.
    if (dataset?.rows?.length) {
      const fromDataset = dataset.rows
        .map((r) => ({
          method: String(r.method || 'GET').toUpperCase(),
          path: String(r.path || r.url || '/'),
          weight: toNumber(r.weight, 1),
        }))
        .filter((t) => t.path);
      if (fromDataset.length) targets = fromDataset;
    }
    if (!targets.length) targets = parsePaths(DEFAULTS.paths);

    await ensureDir(runDir);
    const locustfile = path.join(runDir, 'locustfile.py');
    await fsp.writeFile(locustfile, renderLocustfile(targets, { waitMin: config.waitMin ?? 0.5, waitMax: config.waitMax ?? 2 }), 'utf8');

    const prefix = path.join(runDir, 'locust');
    const args = [
      '-f', locustfile,
      '--headless',
      '-u', String(cfg.users),
      '-r', String(cfg.spawnRate),
      '-t', `${cfg.duration}s`,
      '--host', String(cfg.host),
      '--csv', prefix,
      '--only-summary',
      '--loglevel', 'INFO',
    ];
    if (cfg.extraArgs) args.push(...String(cfg.extraArgs).split(/\s+/).filter(Boolean));

    return {
      command: 'locust',
      args,
      cwd: runDir,
      artifacts: { prefix, locustfile },
      targets,
      durationSec: Number(cfg.duration),
    };
  },

  async simulate({ config, targets }) {
    return simulatePerf({
      users: Number(config.users) || 20,
      spawnRate: Number(config.spawnRate) || 4,
      durationSec: Number(config.duration) || 60,
      targets,
      engine: 'locust',
    });
  },

  async parse({ runDir, prepared }) {
    const prefix = prepared?.artifacts?.prefix ?? path.join(runDir, 'locust');
    const out = { metrics: [], series: [], seriesKeys: [], table: null, report: {} };

    const read = async (suffix) => {
      try {
        return await fsp.readFile(`${prefix}${suffix}`, 'utf8');
      } catch {
        return null;
      }
    };

    const statsRaw = await read('_stats.csv');
    const historyRaw = await read('_stats_history.csv');
    const failuresRaw = await read('_failures.csv');

    if (statsRaw) {
      const { rows } = csvToObjects(statsRaw);
      const pick = (r, key) => {
        const found = Object.keys(r).find((k) => k.trim().toLowerCase() === key.toLowerCase());
        return found ? r[found] : '';
      };
      const endpoints = rows
        .filter((r) => pick(r, 'Name') && pick(r, 'Name') !== 'Aggregated')
        .map((r) => ({
          name: pick(r, 'Name'),
          method: pick(r, 'Type') || '',
          requests: toNumber(pick(r, 'Request Count')),
          failures: toNumber(pick(r, 'Failure Count')),
          avg: toNumber(pick(r, 'Average Response Time')),
          min: toNumber(pick(r, 'Min Response Time')),
          max: toNumber(pick(r, 'Max Response Time')),
          p95: toNumber(pick(r, '95%')),
          p99: toNumber(pick(r, '99%')),
          rps: Number(toNumber(pick(r, 'Requests/s')).toFixed(2)),
        }));

      const agg = rows.find((r) => pick(r, 'Name') === 'Aggregated');
      if (agg) {
        const requests = toNumber(pick(agg, 'Request Count'));
        const failures = toNumber(pick(agg, 'Failure Count'));
        out.metrics = [
          { key: 'requests', label: '总请求数', value: requests, format: 'int' },
          { key: 'rps', label: '平均 RPS', value: Number(toNumber(pick(agg, 'Requests/s')).toFixed(2)), format: 'float' },
          { key: 'avg', label: '平均响应(ms)', value: Math.round(toNumber(pick(agg, 'Average Response Time'))), format: 'int' },
          { key: 'p95', label: 'P95(ms)', value: Math.round(toNumber(pick(agg, '95%'))), format: 'int' },
          { key: 'p99', label: 'P99(ms)', value: Math.round(toNumber(pick(agg, '99%'))), format: 'int' },
          { key: 'errorRate', label: '错误率', value: Number(((failures / Math.max(1, requests)) * 100).toFixed(2)), format: 'percent' },
        ];
        out.report.aggregated = {
          requests,
          failures,
          avg: toNumber(pick(agg, 'Average Response Time')),
          min: toNumber(pick(agg, 'Min Response Time')),
          max: toNumber(pick(agg, 'Max Response Time')),
          median: toNumber(pick(agg, 'Median Response Time')),
          rps: toNumber(pick(agg, 'Requests/s')),
          failPerSec: toNumber(pick(agg, 'Failures/s')),
          p95: toNumber(pick(agg, '95%')),
          p99: toNumber(pick(agg, '99%')),
          totalRps: toNumber(pick(agg, 'Total Requests/s')),
        };
      }
      out.table = {
        title: '接口明细',
        columns: [
          { key: 'name', label: '接口' },
          { key: 'requests', label: '请求数', align: 'right', format: 'int' },
          { key: 'failures', label: '失败', align: 'right', format: 'int' },
          { key: 'avg', label: '平均(ms)', align: 'right', format: 'int' },
          { key: 'p95', label: 'P95(ms)', align: 'right', format: 'int' },
          { key: 'rps', label: 'RPS', align: 'right', format: 'float' },
        ],
        rows: endpoints,
      };
    }

    if (historyRaw) {
      const { rows } = csvToObjects(historyRaw);
      const pick = (r, key) => {
        const found = Object.keys(r).find((k) => k.trim().toLowerCase() === key.toLowerCase());
        return found ? r[found] : '';
      };
      out.series = rows
        .filter((r) => pick(r, 'Name') === 'Aggregated' || !pick(r, 'Name'))
        .map((r) => ({
          t: Math.round(toNumber(pick(r, 'Timestamp'))),
          rps: Number(toNumber(pick(r, 'Requests/s')).toFixed(2)),
          avg: Math.round(toNumber(pick(r, '50%'))),
          p95: Math.round(toNumber(pick(r, '95%'))),
          p99: Math.round(toNumber(pick(r, '99%'))),
          users: toNumber(pick(r, 'User Count')),
          errors: Math.round(toNumber(pick(r, 'Failures/s')) * 10),
        }));
      out.seriesKeys = [
        { key: 'rps', label: 'RPS', color: '#4f9cf9', axis: 'left' },
        { key: 'avg', label: '中位延迟(ms)', color: '#f7b955', axis: 'right' },
        { key: 'p95', label: 'P95(ms)', color: '#e5679b', axis: 'right' },
      ];
    }

    if (failuresRaw) {
      const { rows } = csvToObjects(failuresRaw);
      const pick = (r, key) => {
        const found = Object.keys(r).find((k) => k.trim().toLowerCase() === key.toLowerCase());
        return found ? r[found] : '';
      };
      out.report.failures = rows
        .map((r) => ({
          name: pick(r, 'Name'),
          error: pick(r, 'Error'),
          occurrences: toNumber(pick(r, 'Occurrences')),
        }))
        .filter((r) => r.occurrences > 0)
        .slice(0, 20);
    }

    return out;
  },
};
